// @ts-check
import { defineConfig } from "astro/config";
import react from "@astrojs/react";
import starlight from "@astrojs/starlight";

import { loomDark, loomLight } from "./src/styles/code-theme.js";
import { rehypeTableScroll, rehypeWordmark } from "./src/lib/rehype-wordmark.mjs";
import { rehypeGlossary } from "./src/lib/rehype-glossary.mjs";
import { remarkMermaid } from "./src/lib/remark-mermaid.mjs";
import { expressiveCodePrompt } from "./src/lib/expressive-code-prompt.mjs";
import { DEMOS } from "./src/demos/registry.ts";

// `site` is deliberately unset until there is a domain to put here: Astro uses it for canonical
// URLs and the sitemap, and a wrong one is worse than none.
export default defineConfig({
  // The demos ship three worker modules apiece, and one of them loads SQLite compiled to
  // WebAssembly through a dynamic import. `es` is the format that has one.
  vite: { worker: { format: "es" } },
  markdown: {
    // `remarkMermaid` is a Markdown-stage plugin because it has to claim a ```mermaid fence before
    // Expressive Code turns it into highlighted markup; user plugins run before an integration's,
    // which is what makes that work. It also puts the diagram's source in an attribute, so nothing
    // below can reach into it — see the plugin for why that matters.
    remarkPlugins: [remarkMermaid],
    // `rehypeGlossary` runs before `rehypeWordmark` so the wordmark is never split across an
    // `abbr` boundary, and before `rehypeTableScroll` because it has no interest in tables.
    rehypePlugins: [rehypeGlossary, rehypeWordmark, rehypeTableScroll],
  },
  integrations: [
    react(),
    starlight({
      title: "weftdb",
      description:
        "weftdb is a self-hosted TypeScript toolkit for local-first apps: SQLite persistence, " +
        "schema codegen, offline writes, and HTTP/WebSocket sync.",
      // The landing page at `/` is a plain Astro page, not a Starlight one, so there is no
      // `index.md` in the content collection and Starlight's 404 route would claim `/`
      // otherwise. `src/pages/index.astro` wins either way — Astro's own pages take precedence
      // over injected routes — but leaving the collection without a root page keeps that
      // implicit precedence from being the only thing holding the home page up.
      components: {
        SiteTitle: "./src/components/SiteTitle.astro",
        Head: "./src/components/Head.astro",
      },
      customCss: ["./src/styles/loom.css", "./src/styles/starlight-loom.css"],
      // `social` and `editLink` are left out for the same reason as `site`: the repository has
      // no remote yet, and a link to a URL nobody owns is worse than no link.
      expressiveCode: {
        themes: [loomDark, loomLight],
        plugins: [expressiveCodePrompt()],
        styleOverrides: {
          // The palette tokens rather than the themes' own backgrounds, so a code block is the
          // same recess as an inline `code` span and follows the theme toggle with the page.
          codeBackground: "var(--sunken)",
          borderColor: "var(--rule)",
          borderRadius: "var(--radius-sm)",
          codeFontFamily: "var(--mono)",
          codeFontSize: "13px",
          codeLineHeight: "1.65",
          uiFontFamily: "var(--mono)",
          uiFontSize: "11.5px",
          frames: {
            editorTabBarBackground: "var(--surface)",
            editorTabBarBorderBottomColor: "var(--rule)",
            editorActiveTabBackground: "var(--sunken)",
            editorActiveTabIndicatorTopColor: "var(--accent)",
            editorActiveTabBorderColor: "var(--rule)",
            editorActiveTabForeground: "var(--ink)",
            editorTabBorderRadius: "var(--radius-chip)",
            terminalBackground: "var(--sunken)",
            terminalTitlebarBackground: "var(--surface)",
            terminalTitlebarBorderBottomColor: "var(--rule)",
            terminalTitlebarForeground: "var(--ink-2)",
            shadowColor: "transparent",
          },
        },
      },
      // Explicit rather than autogenerated: autogenerate orders both the groups and the pages
      // inside them alphabetically, which puts Concepts before Guides and "authentication"
      // first in a section that should open with the schema. Each group below autogenerates its
      // own contents, so adding a page is still just adding a file — `sidebar.order` in its
      // frontmatter decides where it lands. Only a new *section* needs an edit here.
      sidebar: [
        {
          label: "Start here",
          items: [{ slug: "introduction" }, { slug: "quick-start" }],
        },
        // One link per demo, from the registry — so a new demo reaches the sidebar by existing,
        // and there is no index page in between to keep in step with the list.
        {
          label: "Demos",
          items: DEMOS.map((demo) => ({ label: demo.title, link: `/demos/${demo.slug}/` })),
        },
        { label: "Guides", items: [{ autogenerate: { directory: "guides" } }] },
        { label: "Concepts", items: [{ autogenerate: { directory: "concepts" } }] },
        { label: "Reference", items: [{ autogenerate: { directory: "reference" } }] },
      ],
      lastUpdated: true,
    }),
  ],
});
